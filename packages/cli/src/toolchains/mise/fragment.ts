import { stringify } from 'smol-toml';
import type { WorkspaceDiscovery } from '#src/core/discovery.js';
import { type MiseEntry, hkMiseConfig } from '#src/toolchains/hk/mise-config.js';

/**
 * Where the generated mise fragment is written, as a POSIX path relative to
 * the root.
 *
 * mise loads every `.toml` in `.config/mise/conf.d/` beside a repository's own
 * config with no `include` to name it, and ranks the repository's own config
 * above it, so a key the repository sets itself still wins.
 */
export const miseFragmentFileName = '.config/mise/conf.d/gtb.toml';

const header = [
  '# Generated by `gtb sync` — do not edit. A key the repository sets in its own',
  '# mise config takes precedence over the one here. Hooks are the exception:',
  '# mise runs the hooks of every file.',
].join('\n');

/*
 * The `mise-setup` action pins the mise every CI job runs, for consumers too,
 * so its version has to stay at or above this floor.
 */
const minVersion: MiseEntry = {
  comment: [
    'The oldest mise that reads `lockfile_version = 3`, which any newer mise',
    'writes on its next `mise lock`. mise enforces the highest floor any file',
    'declares, so a repository\'s own `min_version` can raise this one and never',
    'lower it.',
  ],
  key: 'min_version',
  value: '2026.9.16',
};

const env: readonly MiseEntry[] = [{
  comment: [
    'Opts out of telemetry in every tool that honors the convention',
    '(https://consoledonottrack.com), turbo among them.',
  ],
  key: 'DO_NOT_TRACK',
  value: '1',
}];

const settings: readonly MiseEntry[] = [
  {
    comment: [
      'Records each tool\'s download URLs and checksums in mise.lock, and keeps',
      'the lockfile in step with [tools].',
    ],
    key: 'lockfile',
    value: true,
  },
  {
    comment: [
      'Holds a release back until it has aged, so a compromised publish is likely',
      'caught first. It filters fuzzy and `latest` resolution; an exact pin in',
      '[tools] bypasses it.',
    ],
    key: 'minimum_release_age',
    value: '3d',
  },
  {
    comment: ['gtb\'s own releases are exempt: a fresh one is the one a repository waits for.'],
    key: 'minimum_release_age_excludes',
    value: ['github:gtbuchanan/*', 'npm:@gtbuchanan/*'],
  },
];

/*
 * smol-toml pads an inline array as `[ "a", "b" ]`, which the pre-commit TOML
 * formatter rewrites to `["a", "b"]`, so drop the padding before it can fight
 * `gtb sync` over the file.
 */
const renderValue = (key: string, value: MiseEntry['value']): string =>
  stringify({ [key]: value }).trimEnd().replace(/= \[ (?<items>.*) \]$/v, '= [$<items>]');

const renderEntry = ({ comment, key, value }: MiseEntry): string =>
  [...comment.map(line => `# ${line}`), renderValue(key, value)].join('\n');

const renderTable = (name: string, entries: readonly MiseEntry[]): readonly string[] =>
  (entries.length === 0 ? [] : [[`[${name}]`, ...entries.map(renderEntry)].join('\n')]);

/**
 * Generates the fully-owned mise fragment: the settings every repository using
 * gtb shares, and hk's where the repository configures hk. sync overwrites it
 * wholesale, so it never round-trips the hand-authored mise config.
 */
export const generateMiseFragment = (
  discovery: Pick<WorkspaceDiscovery, 'dependsOnCli' | 'hkFiles' | 'isSelfHosted'>,
): string => {
  const hk = hkMiseConfig(discovery);
  const sections = [
    header,
    renderEntry(minVersion),
    ...renderTable('env', [...env, ...hk?.env ?? []]),
    ...renderTable('hooks', hk?.hooks ?? []),
    ...renderTable('settings', settings),
    ...(hk === undefined ? [] : [stringify({ tasks: hk.tasks }).trimEnd()]),
  ];

  /*
   * Exactly one trailing newline so the generated file matches what hk's
   * end-of-file-fixer wants — otherwise the hook would rewrite it on every
   * commit and fight `gtb sync`.
   */
  return `${sections.join('\n\n')}\n`;
};
